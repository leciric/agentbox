// Builds the live view of `agentbox machines serve`'s page into
// internal/machinesweb/static/vnc.js: the app's VNC client (noVNC and
// lib/vncSession.ts) as one script, embedded in the Go binary like the rest of
// the page. It is committed, so building AgentBox needs no Node; CI rebuilds it
// and fails when it differs.
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
await build({
  entryPoints: [join(root, 'src/machines/view.ts')],
  outfile: join(root, '../internal/machinesweb/static/vnc.js'),
  bundle: true,
  format: 'esm', // noVNC awaits at its top level
  target: 'es2022',
  minify: true,
  legalComments: 'eof',
  banner: {
    js: [
      '// Generated by desktop/scripts/build-machines-view.mjs from desktop/src/machines/view.ts: do not edit.',
      '// Includes noVNC (https://github.com/novnc/noVNC), Copyright (C) The noVNC authors, licensed under the',
      '// Mozilla Public License 2.0 (https://mozilla.org/MPL/2.0/); its source is the @novnc/novnc package.',
    ].join('\n'),
  },
  logLevel: 'warning',
});
