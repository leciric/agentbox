// Writes both apps' tokens from desktop/src/shared/design-tokens.json:
//
//   desktop/src/renderer/tokens.css      the Electron app's custom properties
//                                        (--ab-*) and its Tailwind theme
//   native/crates/app/src/theme/tokens.rs the native app's palettes and scales
//
//   node desktop/scripts/tokens.mjs           write them
//   node desktop/scripts/tokens.mjs --check   exit 1 if either is stale
//
// tokens.test.ts runs the same check, and the native crate's own test compares
// SOURCE_HASH with the JSON it was generated from.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const sourcePath = join(root, 'desktop/src/shared/design-tokens.json');
export const cssPath = join(root, 'desktop/src/renderer/tokens.css');
export const rustPath = join(root, 'native/crates/app/src/theme/tokens.rs');

// parse reads "#rrggbb" or "#rrggbb/alpha".
function parse(value) {
  const m = /^#([0-9a-f]{6})(?:\/([0-9.]+))?$/i.exec(value);
  if (!m) throw new Error(`not a colour: ${value}`);
  return { hex: m[1].toLowerCase(), alpha: m[2] === undefined ? null : Number(m[2]) };
}

function cssColor(value) {
  const { hex, alpha } = parse(value);
  if (alpha === null) return `#${hex}`;
  const n = parseInt(hex, 16);
  return `rgb(${n >> 16} ${(n >> 8) & 255} ${n & 255} / ${alpha})`;
}

function rustColor(value) {
  const { hex, alpha } = parse(value);
  return alpha === null ? `op(0x${hex})` : `a(0x${hex}, ${alpha.toFixed(3).replace(/0+$/, '').replace(/\.$/, '.0')})`;
}

// fnv is FNV-1a over the source's bytes: the native test computes the same.
export function fnv(text) {
  let h = 0x811c9dc5;
  for (const b of Buffer.from(text, 'utf8')) {
    h ^= b;
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h >>> 0;
}

const scale = (o) => Object.entries(o).filter(([k]) => k !== '//');
const rem = (px) => `${px / 16}rem`;

function cssShadow(layers) {
  return layers
    .map(([x, y, blur, spread, role, strength]) => {
      const colour = strength === 1 ? `var(--ab-${role})` : `color-mix(in srgb, var(--ab-${role}) ${strength * 100}%, transparent)`;
      return `${x} ${y}px ${blur}px ${spread}px ${colour}`.replace(/^0 0px/, '0 0');
    })
    .join(', ');
}

export function css(tokens) {
  const { dark, light } = tokens.color;
  const block = (colors) =>
    Object.entries(colors)
      .map(([k, v]) => `  --ab-${k}: ${cssColor(v)};`)
      .join('\n');
  const theme = [
    ...scale(tokens.text).map(([k, v]) => `  --text-${k}: ${rem(v)};`),
    ...scale(tokens.radius).map(([k, v]) => `  --radius-${k}: ${rem(v)};`),
    ...scale(tokens.space).map(([k, v]) => `  --spacing-${k}: ${rem(v)};`),
    ...scale(tokens.elevation).map(([k]) => `  --shadow-${k}: var(--ab-shadow-${k});`),
  ].join('\n');
  return `/* Generated by desktop/scripts/tokens.mjs from src/shared/design-tokens.json.
   Do not edit: change the JSON and run it again. styles.css says what each
   role is for. */
:root {
${block(dark)}
${scale(tokens.elevation)
  .map(([k, v]) => `  --ab-shadow-${k}: ${cssShadow(v)};`)
  .join('\n')}
}

:root[data-appearance="light"],
[data-appearance-scope="light"] {
${block(light)}
}

@theme {
${theme}
}
`;
}

