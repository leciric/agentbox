export function rust(tokens, source) {
  const { dark, light } = tokens.color;
  const used = new Set(fields.flatMap((f) => (Array.isArray(f) ? f[1] : [f])));
  for (const k of Object.keys(dark)) if (!used.has(k)) throw new Error(`${k} has no field in the native Palette`);
  for (const k of Object.keys(light)) if (!(k in dark)) throw new Error(`light's ${k} is not a role of dark`);
  const palette = (name, look, colors, doc) => {
    const lines = fields.map((f) => {
      if (Array.isArray(f)) return `    ${f[0]}: [\n${f[1].map((k) => `        ${rustColor(colors[k])},`).join('\n')}\n    ],`;
      return `    ${f.replaceAll('-', '_')}: ${rustColor(colors[f])},`;
    });
    return `/// ${doc}\npub const ${name}: Palette = Palette {\n    look: Look::${look},\n${lines.join('\n')}\n};`;
  };
  const consts = (o, name) =>
    scale(o)
      .map(([k, v]) => `    pub const ${(/^\d/.test(k) ? name(k) : k).toUpperCase()}: Pixels = px(${v}.);`)
      .join('\n');
  const shadow = (k, layers) =>
    `pub const ${k.toUpperCase()}: &[Layer] = &[\n${layers
      .map(([x, y, blur, spread, role, strength]) => `    Layer { x: ${x}., y: ${y}., blur: ${blur}., spread: ${spread}., deep: ${role === 'shadow-deep'}, strength: ${strength.toFixed(2)} },`)
      .join('\n')}\n];`;
  return `//! Generated by desktop/scripts/tokens.mjs from
//! desktop/src/shared/design-tokens.json, which the Electron app's tokens.css
//! is generated from too. Do not edit: change the JSON and run it again.
#![cfg_attr(rustfmt, rustfmt_skip)]

use super::{Look, Palette, a, op};

/// SOURCE_HASH is FNV-1a of the JSON this was generated from; a test compares
/// it with the file's, so a stale copy fails.
pub const SOURCE_HASH: u32 = 0x${fnv(source).toString(16).padStart(8, '0')};

${palette('DARK', 'Dark', dark, "DARK is AgentBox's own look, and the default.")}

${palette('LIGHT', 'Light', { ...dark, ...light }, 'LIGHT is the same roles on a white window.')}

/// The radii: sm a chip or a key, md a row, lg a button or an input, xl a
/// card, xxl a dialog or the composer, xxxl the largest sheet.
pub mod radius {
    use gpui::{Pixels, px};
${consts(tokens.radius, (k) => (k === '2xl' ? 'xxl' : 'xxxl'))}
}

/// The type scale, six sizes and nothing between.
pub mod text {
    use gpui::{Pixels, px};
${consts(tokens.text)}
}

/// Spacing, a 4px grid.
pub mod space {
    use gpui::{Pixels, px};
${consts(tokens.space)}
}

/// Layer is one drop of a shadow: its offset, blur and spread in pixels, and
/// which of the palette's two shadow colours it is, at what strength.
pub struct Layer {
    pub x: f32,
    pub y: f32,
    pub blur: f32,
    pub spread: f32,
    pub deep: bool,
    pub strength: f32,
}

/// Elevation: what a menu or popover casts, and what a dialog does. A panel
/// at rest casts nothing.
${scale(tokens.elevation)
  .map(([k, v]) => shadow(k, v))
  .join('\n')}
`;
}

export function generate() {
  const source = readFileSync(sourcePath, 'utf8');
  const tokens = JSON.parse(source);
  return { [cssPath]: css(tokens), [rustPath]: rust(tokens, source) };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  let stale = false;
  for (const [path, text] of Object.entries(generate())) {
    if (check) {
      let now = '';
      try {
        now = readFileSync(path, 'utf8');
      } catch {}
      if (now !== text) {
        console.error(`${path} is stale: run node desktop/scripts/tokens.mjs`);
        stale = true;
      }
    } else {
      writeFileSync(path, text);
      console.log(`wrote ${path}`);
    }
  }
  process.exit(stale ? 1 : 0);
}
